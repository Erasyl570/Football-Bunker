# Хранилище использованных карт для каждого чата (лобби)
_used_cards_by_chat = {}

def clear_lobby(chat_id: int):
    """Сбрасывает память карт при новом запуске игры в чате."""
    if chat_id in _used_cards_by_chat:
        del _used_cards_by_chat[chat_id]

def generate_player_pack(chat_id: int) -> dict:
    """Генерирует уникальный набор форварда без повторов в текущем лобби."""
    if chat_id not in _used_cards_by_chat:
        _used_cards_by_chat[chat_id] = {
            "pos": [], "hp": [], "sk": [], "inv": [], "sec": []
        }
    
    used = _used_cards_by_chat[chat_id]

    def get_unique(pool: list, used_list: list) -> str:
        available = [x for x in pool if x not in used_list]
        if not available:  # Если игроков больше, чем элементов в пуле, очищаем и берем по новой
            used_list.clear()
            available = pool
        choice = random.choice(available)
        used_list.append(choice)
        return choice

    age = random.randint(16, 35)
    pos = get_unique(POSITIONS, used["pos"])

    return {
        "position": f"{pos}, {age} лет",
        "health": get_unique(HEALTH_POOL, used["hp"]),
        "skill": get_unique(SKILL_POOL, used["sk"]),
        "inventory": get_unique(INVENTORY_POOL, used["inv"]),
        "secret": get_unique(SECRET_POOL, used["sec"])
    }

def generate_scenario(players_count: int) -> dict:
    club = random.choice(CLUBS)
    winners_needed = max(1, players_count // 2)
    
    scenarios = [
        f"📉 <b>КРИЗИС АТАКИ В {club.upper()}!</b>\nРуководство в ярости от плохой реализации. Клуб ищет <b>{winners_needed} форварда(ов)</b> в основу, остальные идут на выход.",
        f"🦠 <b>ЭПИДЕМИЯ В {club.upper()}!</b>\nПоловина нападающих отравилась перед матчем. Остаться в составе смогут только <b>{winners_needed}</b> самых стойких.",
        f"🔥 <b>МЕГА-ТРАНСФЕР В {club.upper()}!</b>\nТренер меняет схему под атаку. Контракт получат только <b>{winners_needed}</b> лучших форварда по итогам обсуждений."
    ]
    
    return {
        "club": club,
        "winners_needed": winners_needed,
        "text": random.choice(scenarios)
    }
