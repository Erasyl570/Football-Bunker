def generate_game_packs(players_count: int) -> list:
    """Генерирует список уникальных наборов карточек на всю игру без повторов."""
    # Берем случайные уникальные элементы для каждого пула на всю компанию
    positions = [f"{p}, {random.randint(16, 35)} лет" for p in random.choices(POSITIONS, k=players_count)]
    healths = random.sample(HEALTH_POOL, players_count)
    skills = random.sample(SKILL_POOL, players_count)
    inventories = random.sample(INVENTORY_POOL, players_count)
    secrets = random.sample(SECRET_POOL, players_count)

    packs = []
    for i in range(players_count):
        packs.append({
            "position": positions[i],
            "health": healths[i],
            "skill": skills[i],
            "inventory": inventories[i],
            "secret": secrets[i]
        })
    return packs

