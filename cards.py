# Уникальная генерация без повторов внутри одного лобби
_used_cards = {}

def clear_lobby(chat_id: int):
    if chat_id in _used_cards:
        del _used_cards[chat_id]

def generate_player_pack(chat_id: int):
    if chat_id not in _used_cards:
        _used_cards[chat_id] = {p: [] for p in ["pos", "hp", "sk", "inv", "sec"]}
    
    u = _used_cards[chat_id]
    
    def get_u(pool, used_list):
        available = [x for x in pool if x not in used_list]
        choice = random.choice(available if available else pool)
        used_list.append(choice)
        return choice

    return {
        "position": get_u(POSITIONS, u["pos"]),
        "health": get_u(HEALTH_POOL, u["hp"]),
        "skill": get_u(SKILL_POOL, u["sk"]),
        "inventory": get_u(INVENTORY_POOL, u["inv"]),
        "secret": get_u(SECRET_POOL, u["sec"])
    }

