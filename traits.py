_SALARIES = [4, 6, 8, 10, 12, 15, 20, 25]
_CLAUSES = [40, 60, 80, 100, 120, 150, 200]


def make_contract(rng, year=None) -> str:
    year = year or datetime.date.today().year
    years = rng.randint(1, 5)
    salary = rng.choice(_SALARIES)
    clause = rng.choice(_CLAUSES)
    word = "год" if years == 1 else ("года" if years in (2, 3, 4) else "лет")
    return f"до {year + years} ({years} {word}), зарплата €{salary}M/год, отступные €{clause}M"


def parse_contract(text) -> dict:
    s = str(text or "")
    years = re.search(r"\((\d+)\s*[а-яё]+\)", s)
    salary = re.search(r"зарплата\s*€\s*(\d+)", s)
    clause = re.search(r"отступные\s*€\s*(\d+)", s)
    return {
        "years": int(years.group(1)) if years else None,
        "salary": int(salary.group(1)) if salary else None,
        "clause": int(clause.group(1)) if clause else None,
    }
