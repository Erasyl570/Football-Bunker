def _domains_for(text: str) -> set:
    low = text.lower()
    found = set()
    for domain, keys in _DOMAIN_RULES:
        if any(k in low for k in keys):
            found.add(domain)
    return found


def _register_skill(text: str, cls: str, role: str):
    SKILL_CLASS[text] = cls
    if cls == "good":
        SKILL_DOMAINS[text] = {"goalkeeping"} if role == "goalkeeper" else _domains_for(text)
    else:
        SKILL_DOMAINS.pop(text, None)


def _add_unique(lst: list, item: str):
    if item not in lst:
        lst.append(item)


def extend_pools(positions, skills, health, inventories, secrets,
                 club_squads, club_infra, club_reputation, club_finance):
    """Дополняет исходные пулы из cards.py и регистрирует теги. Идемпотентна."""
    # --- позиции / навыки ---
    for gk in GK_POSITIONS:
        positions.setdefault("goalkeeper", [])
        _add_unique(positions["goalkeeper"], gk)
    orig_len = {"attacker": 50, "defender": 37, "midfielder": 34}
    for role in ("attacker", "defender", "midfielder"):
        bad_idx = _SKILL_BAD_IDX[role]
        # Исходные строки идут первыми — классифицируем только их, по индексам.
        for i, text in enumerate(list(skills[role])[:orig_len[role]]):
            _register_skill(text, "bad" if i in bad_idx else "good", role)
        for text, cls in SKILLS_EXTRA[role]:
            _add_unique(skills[role], text)
            _register_skill(text, cls, role)
    skills.setdefault("goalkeeper", [])
    for text, cls in GK_SKILLS:
        _add_unique(skills["goalkeeper"], text)
        _register_skill(text, cls, "goalkeeper")

    # --- здоровье ---
    base_health = list(health[:])
    for i, text in enumerate(base_health):
        if i >= 58:
            break
        if i in _HEALTH_GOOD_IDX:
            HEALTH_CLASS[text] = "good"
        elif i in _HEALTH_BAD_IDX:
            HEALTH_CLASS[text] = "bad"
        else:
            HEALTH_CLASS[text] = "meh"
    # опечатка в исходной строке
    for i, text in enumerate(health):
        if text == "Имеется Проблемы с сердцем":
            health[i] = "Проблемы с сердцем (требуется регулярное наблюдение)"
            HEALTH_CLASS[health[i]] = "bad"
            HEALTH_CLASS.pop(text, None)
    for text, cls in HEALTH_EXTRA:
        _add_unique(health, text)
        HEALTH_CLASS[text] = cls

    # --- багаж ---
    if len(inventories) > 19 and inventories[19] == "Допинг":
        inventories[19] = DOPING_ITEM_TEXT
    for i, text in enumerate(list(inventories)):
        if i >= 48:
            break
        flags = set()
        if i in _ITEM_MEDICAL_IDX:
            flags.add("medical")
        if i in _ITEM_PR_IDX:
            flags.add("pr")
        if i in _ITEM_ANALYTICS_IDX:
            flags.add("analytics")
        if i in _ITEM_DOPING_IDX:
            flags.add("doping")
        ITEM_FLAGS[text] = flags
    for text, flags in INVENTORY_EXTRA:
        _add_unique(inventories, text)
        ITEM_FLAGS[text] = set(flags)

    # --- секреты ---
    for i, text in enumerate(list(secrets)):
        if i >= 45:
            break
        flags = set()
        if i in _SECRET_DOPING_IDX:
            flags.add("doping")
        if i in _SECRET_GAMBLING_IDX:
            flags.add("gambling")
        if i in _SECRET_MEDIA_IDX:
            flags.add("media")
        if i in _SECRET_LEAVING_IDX:
            flags.add("leaving")
        if i in _SECRET_HIDDEN_INJURY_IDX:
            flags.add("hidden_injury")
        SECRET_FLAGS[text] = flags
    for text, flags in SECRETS_EXTRA:
        _add_unique(secrets, text)
        SECRET_FLAGS[text] = set(flags)

    # --- клубы ---
    for field, lst, table in (("squad", club_squads, _CLUB_SQUAD_TAGS),
                              ("infrastructure", club_infra, _CLUB_INFRA_TAGS),
                              ("reputation", club_reputation, _CLUB_REP_TAGS),
                              ("finance", club_finance, _CLUB_FIN_TAGS)):
        for i, text in enumerate(lst):
            CLUB_TAGS[(field, text)] = set(table.get(i, set()))


